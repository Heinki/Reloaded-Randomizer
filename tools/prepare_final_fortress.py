"""Compile a playable Fortress artifact using this installation's owned loadout.

This writes to a separate output directory, without launching a game or changing
progression. Copying runtime files into the game root remains the launcher's job.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from randomizer.core.paths import GAME_ROOT, CAMEO_CACHE_DIR
from randomizer.core.storage import atomic_write_text, atomic_write_json
from randomizer.final_fortress.catalogue import COUNTRY_LABELS
from randomizer.final_fortress.config import load_config, DIFFICULTY_IDS
from randomizer.final_fortress.engine import build_map, spawn_data, _MapWriter
from randomizer.final_fortress.native import installed_rules_registry
from randomizer.final_fortress.persistence import FinalFortressRepository
from randomizer.final_fortress.profiles import PROFILE_PATHS, STANDARD_PROFILE
from randomizer.final_fortress.planning import build_run_plan
from randomizer.maps.ini import IniLines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--profile', choices=tuple(PROFILE_PATHS), default=STANDARD_PROFILE,
                        help='Use an existing local profile; never changes its progression.')
    parser.add_argument('--faction', choices=tuple(COUNTRY_LABELS.values()), default='Allies')
    parser.add_argument('--difficulty', choices=DIFFICULTY_IDS, default='normal')
    parser.add_argument('--multiplier', type=int, choices=range(1, 11), default=1)
    parser.add_argument('--seed', default=None)
    args = parser.parse_args()
    output = args.output.resolve()
    if output == GAME_ROOT.resolve():
        parser.error('Use a separate output directory; the launcher owns runtime deployment.')
    config = load_config()
    state = FinalFortressRepository(PROFILE_PATHS[args.profile]).load()
    preferences = state['preferences']
    country = next(country for country, name in COUNTRY_LABELS.items() if name == args.faction)
    plan = build_run_plan(config, difficulty=args.difficulty,
                         seed=args.seed or 'RFF-' + uuid.uuid4().hex,
                         player_country=country, selected_perks=state['selected_perks'],
                         perk_ranks=state['perk_ranks'], wave_multiplier=args.multiplier,
                         selected_challenges=preferences['selected_challenges'],
                         challenge_stacks=preferences['challenge_stacks'])
    run = {'id': uuid.uuid4().hex, 'status': 'active', 'config': config,
           'plan': plan, 'claimed_events': []}
    _, rules = installed_rules_registry()
    preloads = {}
    data = build_map(GAME_ROOT, run, rules, preloads=preloads)
    output.mkdir(parents=True, exist_ok=True)
    atomic_write_text(output / 'spawnmap.ini', data.decode('latin-1'), encoding='latin-1')
    atomic_write_text(output / 'spawn.ini', spawn_data(plan, data).decode('latin-1'), encoding='latin-1')
    for key, name in (('rules', 'rulesmd.ini'), ('ai', 'aimd.ini')):
        writer = _MapWriter(IniLines((CAMEO_CACHE_DIR / name).read_text(
            encoding='utf-8', errors='ignore').splitlines()))
        writer.sections.update(preloads[key])
        atomic_write_text(output / name, '; Generated by C&C Reloaded Randomizer Launcher Final Fortress\r\n'
                          + writer.finish(replace_sections=(('AITriggerTypes', 'AITriggerTypesEnable')
                              if key == 'ai' else ())).decode('latin-1'), encoding='latin-1')
    atomic_write_json(output / 'run.json', run)
    print(f'Prepared {args.profile}: {args.faction}, {args.difficulty}, x{args.multiplier}: {output}')
    print('Map SHA256: ' + hashlib.sha256(data).hexdigest())


if __name__ == '__main__':
    main()
